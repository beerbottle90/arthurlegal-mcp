def _xtime(a: int) -> int:
    a <<= 1
    return (a ^ 0x1b) & 0xff if a & 0x100 else a


def _expand_key(key: bytes):
    nk = len(key) // 4
    rounds = nk + 6
    w = [list(key[4 * i:4 * i + 4]) for i in range(nk)]
    for i in range(nk, 4 * (rounds + 1)):
        t = list(w[i - 1])
        if i % nk == 0:
            t = t[1:] + t[:1]
            t = [_SBOX[b] for b in t]
            t[0] ^= _RCON[i // nk - 1]
        elif nk > 6 and i % nk == 4:
            t = [_SBOX[b] for b in t]
        w.append([w[i - nk][j] ^ t[j] for j in range(4)])
    return [sum(w[4 * r:4 * r + 4], []) for r in range(rounds + 1)], rounds


def _encrypt_block(block: bytes, rk, rounds: int) -> bytes:
    s = [b ^ k for b, k in zip(block, rk[0])]
    for r in range(1, rounds + 1):
        s = [_SBOX[b] for b in s]
        # ShiftRows (state is column-major: s[c*4 + r])
        s = [s[(i + 4 * (i % 4)) % 16] for i in range(16)]
        if r != rounds:
            out = []
            for c in range(4):
                a0, a1, a2, a3 = s[4 * c:4 * c + 4]
                out += [
                    _xtime(a0) ^ (_xtime(a1) ^ a1) ^ a2 ^ a3,
                    a0 ^ _xtime(a1) ^ (_xtime(a2) ^ a2) ^ a3,
                    a0 ^ a1 ^ _xtime(a2) ^ (_xtime(a3) ^ a3),
                    (_xtime(a0) ^ a0) ^ a1 ^ a2 ^ _xtime(a3),
                ]
            s = out
        s = [b ^ k for b, k in zip(s, rk[r])]
    return bytes(s)


def aes_cbc_encrypt(key: bytes, iv: bytes, plaintext: bytes) -> bytes:
    """AES-CBC with PKCS#7 padding. ``key`` may be 16, 24 or 32 bytes."""
    if len(key) not in (16, 24, 32):
        raise ValueError("AES key must be 16/24/32 bytes")
    if len(iv) != 16:
        raise ValueError("IV must be 16 bytes")
    pad = 16 - (len(plaintext) % 16)
    data = plaintext + bytes([pad]) * pad
    rk, rounds = _expand_key(key)
    out = bytearray()
    prev = iv
    for i in range(0, len(data), 16):
        block = bytes(a ^ b for a, b in zip(data[i:i + 16], prev))
        prev = _encrypt_block(block, rk, rounds)
        out += prev
    return bytes(out)


